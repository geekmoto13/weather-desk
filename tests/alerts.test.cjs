const assert = require('node:assert/strict');
const {view,kind,pointKey,officialUrl} = require('../static/alerts.js');
const now = 1792699200;
const warning = {id:'test-warning',event:'Severe Thunderstorm Warning',validUntil:now+60,expiresAt:now+60};
const watch = {id:'test-watch',event:'Flood Watch',validUntil:now+3600};
const data = {checkedAt:now-10,alerts:[warning,watch],stale:false,error:null};
assert.equal(view(null,now).status,'loading');
assert.equal(view({...data,alerts:[]},now).status,'quiet');
assert.equal(view(data,now).status,'active');
assert.equal(view(data,now).tone,'warning');
assert.equal(view(data,now).title,'Severe Thunderstorm Warning + 1 more');
assert.equal(view(data,now+60).title,'Flood Watch');
assert.equal(view(data,now+3600).status,'unavailable');
assert.equal(view({...data,checkedAt:now-181},now).status,'stale');
assert.equal(view({...data,checkedAt:now+61},now).status,'stale');
assert.equal(view({...data,error:'offline'},now).title,'Last known: Severe Thunderstorm Warning + 1 more');
assert.equal(view({...data,alerts:[],stale:true},now).title,'NWS alerts unavailable');
assert.equal(view({alerts:[],checkedAt:null},now).status,'unavailable');
assert.equal(kind('Tornado Watch'),'watch');
assert.equal(kind('Coastal Flood Advisory'),'advisory');
assert.equal(kind('Special Weather Statement'),'statement');
assert.equal(pointKey({latitude:42.4668,longitude:-70.9495}),'42.4668,-70.9495');
assert.equal(pointKey(null),'');
assert.equal(officialUrl({latitude:42.4668,longitude:-70.9495}),'https://forecast.weather.gov/MapClick.php?lat=42.4668&lon=-70.9495');
assert.equal(officialUrl(null),'https://www.weather.gov/');
console.log('Alert presentation: active, expired, multiple, stale, failed, future-clock and location states passed.');
