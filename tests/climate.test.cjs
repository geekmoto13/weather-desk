const assert=require('node:assert/strict');
const climate=require('../static/climate.js');
const now=Date.parse('2026-10-22T15:00:00Z')/1000;
const data={schemaVersion:2,date:'2026-10-22',stale:false,normal:{through:'2026-10-22',rainMonthToDateIn:2.86,rainYearToDateIn:34.46},records:{high:{valueF:83,years:[1979]},low:{valueF:28,years:[1940]},rain:{valueIn:1.53,years:[1898]}}};
const observation={timestamp:now,rainMonthMm:2.14*25.4,rainYearMm:40*25.4};
let ref=climate.reference(data,observation,now);
assert.equal(ref.high.valueF,83);assert.deepEqual(ref.rain.years,[1898]);
assert.equal(ref.month.kind,'below');assert.equal(ref.month.difference,-.72);
assert.equal(ref.year.kind,'above');assert.equal(ref.year.difference,5.54);
assert.equal(climate.compare(2.86*25.4,2.86).kind,'at');
assert.equal(climate.compare(1.014*25.4,1.006).kind,'at','Equal displayed hundredths must not get conflicting arrows');
assert.equal(climate.compare(0,0).kind,'at');
assert.equal(climate.compare(0,.01).kind,'below');
assert.equal(climate.compare(null,0).kind,'unknown','A missing sensor counter must not become zero');
assert.equal(climate.compare(1,NaN).kind,'unknown');
assert.equal(climate.compare(-1,1).kind,'unknown');
assert.equal(climate.reference(data,{...observation,timestamp:now-901},now).month.kind,'unknown','Stale station totals must not get a current comparison');
assert.equal(climate.reference(data,{...observation,timestamp:now+301},now).year.kind,'unknown');
assert.equal(climate.reference(data,{...observation,timestamp:now-86400},now).month.kind,'unknown');
assert.equal(climate.reference(data,{...observation,rainYearTimestamp:now-901},now).year.kind,'unknown','A history-sourced annual counter keeps its own freshness');
assert.equal(climate.reference(data,{...observation,rainYearTimestamp:now-300},now).year.kind,'above');
const midnight=Date.parse('2026-10-22T04:02:00Z')/1000;
assert.equal(climate.reference(data,{...observation,timestamp:midnight,rainYearTimestamp:midnight-300},midnight).year.kind,'unknown','A recent previous-day annual counter cannot get today’s comparison');
ref=climate.reference({...data,date:'2026-10-21'},observation,now);
assert.equal(ref.high,null);assert.equal(ref.monthNormal,null);assert.equal(ref.month.kind,'unknown');
ref=climate.reference({...data,schemaVersion:1},observation,now);
assert.equal(ref.high.valueF,83,'An older same-date cache can still supply a labeled temperature record');
assert.equal(ref.monthNormal,null,'Older completed-day Boston totals must not be used for the personal station comparison');
ref=climate.reference({...data,stale:true},observation,now);
assert.equal(ref.cached,true);assert.equal(ref.month.kind,'below');
assert.equal(climate.reference(null,observation,now).rain,null);
assert.equal(climate.bostonDay(Date.parse('2026-10-22T03:59:00Z')/1000),'2026-10-21');
assert.equal(climate.bostonDay(Date.parse('2026-10-22T04:00:00Z')/1000),'2026-10-22');
assert.equal(climate.bostonDay(1e30),null);
const rainData={schemaVersion:2,stationId:'BOSthr',date:'2026-10-22',through:'2026-10-22',throughYear:2025,startYear:1872,stale:false,month:{wettest:{valueIn:10.29,years:[1996]},driest:{valueIn:0,trace:true,years:[1947]}},year:{wettest:{valueIn:52.80,years:[1958]},driest:{valueIn:19.88,years:[1965]}}};
let rainRefs=climate.rainRecords(rainData,now);
assert.equal(rainRefs.monthWettest.valueIn,10.29);assert.equal(rainRefs.monthDriest.trace,true);
assert.equal(rainRefs.yearWettest.valueIn,52.8);assert.equal(rainRefs.yearDriest.valueIn,19.88);
assert.equal(climate.rainRecords({...rainData,stale:true},now).cached,true);
assert.equal(climate.rainRecords({...rainData,schemaVersion:1},now).yearWettest,null,'Full-period caches must not become YTD records');
assert.equal(climate.rainRecords({...rainData,date:'2026-10-21'},now).yearWettest,null,'Records for a different cutoff date cannot be reused');
assert.equal(climate.rainRecords({...rainData,through:'2026-10-21'},now).monthWettest,null);
assert.equal(climate.rainRecords({...rainData,throughYear:2024},now).monthWettest,null);
assert.equal(climate.rainRecords({...rainData,stationId:'Another'},now).yearWettest,null);
assert.equal(climate.rainRecords(rainData,Date.parse('2026-11-01T05:00:00Z')/1000).monthWettest,null);
assert.equal(climate.rainRecords(null,now).yearWettest,null);
console.log('Local rainfall arrows, display precision, missing/stale totals, cache schema and Boston date checks passed.');

const monthlyClimate={...data,stationId:'BOSthr',normalPeriod:'1991–2020',normal:{...data.normal,rainMonths:[
 {month:1,start:'2026-01-01',through:'2026-01-31',normalIn:3.39,missingNormalDays:0},
 {month:7,start:'2026-07-01',through:'2026-07-31',normalIn:3.27,missingNormalDays:0},
 {month:10,start:'2026-10-01',through:'2026-10-22',normalIn:2.86,missingNormalDays:0}]}};
const monthlyAnnual={year:2026,through:'2026-10-22'};
const jan={month:1,inches:.88,method:'month-end counter'};
const july={month:7,inches:5.48,method:'month-end counter'};
const oct={month:10,inches:2.70,method:'live month to date',timestamp:now};
let monthRef=climate.monthlyReference(monthlyClimate,monthlyAnnual,jan,observation,now);
assert.equal(monthRef.normalIn,3.39);assert.equal(monthRef.comparison.kind,'below');assert.equal(monthRef.comparison.difference,-2.51);
assert.equal(climate.monthlyReference(monthlyClimate,monthlyAnnual,july,observation,now).comparison.difference,2.21);
assert.equal(climate.monthlyReference(monthlyClimate,monthlyAnnual,{...jan,inches:3.39},observation,now).comparison.kind,'at');
assert.equal(climate.monthlyReference(monthlyClimate,monthlyAnnual,oct,observation,now).comparison.difference,-.16);
assert.equal(climate.monthlyReference(monthlyClimate,monthlyAnnual,{...jan,inches:null},observation,now).comparison.kind,'unknown');
assert.equal(climate.monthlyReference(monthlyClimate,monthlyAnnual,oct,{...observation,timestamp:now-901},now).comparison.kind,'unknown');
assert.equal(climate.monthlyReference(monthlyClimate,monthlyAnnual,{...oct,timestamp:now-901},observation,now).comparison.kind,'unknown');
assert.equal(climate.monthlyReference(monthlyClimate,monthlyAnnual,jan,{...observation,timestamp:now-901},now).comparison.kind,'below','Completed months remain valid historical comparisons');
assert.equal(climate.monthlyReference(monthlyClimate,{...monthlyAnnual,through:'2026-10-21'},oct,observation,now).normalIn,null,'Do not compare different MTD windows');
assert.equal(climate.monthlyReference(monthlyClimate,{...monthlyAnnual,year:2025},jan,observation,now).normalIn,null);
assert.equal(climate.monthlyReference({...monthlyClimate,stationId:'Another'},monthlyAnnual,jan,observation,now).normalIn,null);
assert.equal(climate.monthlyReference(data,monthlyAnnual,jan,observation,now).normalIn,null,'Legacy cache has no monthly normals');
const missingNormal=structuredClone(monthlyClimate);missingNormal.normal.rainMonths[0].missingNormalDays=1;
assert.equal(climate.monthlyReference(missingNormal,monthlyAnnual,jan,observation,now).normalIn,null);
assert.equal(climate.monthlyReference({...monthlyClimate,stale:true},monthlyAnnual,jan,observation,now).cached,true);
console.log('Monthly normals: matching full/partial windows, above/at/below, historical vs live freshness, missing data and cache rules passed.');
